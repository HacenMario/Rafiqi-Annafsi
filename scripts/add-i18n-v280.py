for lang, cfg in [("fr", BLOCKS["fr"]), ("en", BLOCKS["en"])]:
    p = f"src/lib/i18n/{lang}.ts"
    s = io.open(p, encoding="utf-8").read()

    # 1) nav.important — بعد سطر notifications داخل قسم nav (أول ظهور)
    key, add = cfg["nav_after"]
    idx = s.find(key)
    assert idx > 0, f"{lang}: nav anchor"
    eol = s.index("\n", idx) + 1
    s = s[:eol] + add + s[eol:]

    # 2..5) أقسام victim/counselor/settings/admin — بعد أول مفتاح مطابق داخل القسم
    for name in ("victim_after", "counselor_after", "settings_after", "admin_after"):
        key, add = cfg[name]
        idx = s.find(key)
        assert idx > 0, f"{lang}: {name} anchor ({key[:30]})"
        eol = s.index("\n", idx) + 1
        s = s[:eol] + add + s[eol:]

    # 6) الأقسام الجديدة قبل إغلاق الكائن النهائي
    if lang == "ar":
        anchor = "export type Dict = typeof ar;"
        assert anchor in s, f"{lang}: dict anchor"
        s = s.replace(anchor, cfg["sections"] + "\n" + anchor)
    else:
        # fr/en: أدرج قبل « };» الختامية الأخيرة (القسم السابق ينتهي بفاصلة دائماً)
        idx = s.rfind("\n};")
        assert idx > 0, f"{lang}: closing anchor"
        s = s[:idx + 1] + cfg["sections"] + s[idx:]

    io.open(p, "w", encoding="utf-8").write(s)
    print(f"{lang}.ts updated")
print("ALL i18n DONE")
